const mongoose = require('mongoose');


// ============================================================
// 🖼️ IMAGE DE RÉFÉRENCE
// ============================================================

const PlantImageSchema = new mongoose.Schema(
  {
    // ----------------------------------------------------------
    // URL / CHEMIN DE L'IMAGE
    // ----------------------------------------------------------

    url: {
      type: String,
      required: true,
      trim: true
    },

    // ----------------------------------------------------------
    // VUE DE LA PLANTE
    // ----------------------------------------------------------

    vue: {
      type: String,
      enum: [
        'front',
        'side',
        'top',
        'close-up',
        'far'
      ],
      required: true
    }
  },
  {
    _id: true
  }
);


// ============================================================
// 💬 RETOUR D'UNE AUTRE PERSONNE
// ============================================================

const PlantRetourSchema = new mongoose.Schema(
  {
    // ----------------------------------------------------------
    // NOM DE LA PERSONNE
    // ----------------------------------------------------------

    nom: {
      type: String,
      trim: true,
      default: 'Utilisateur'
    },

    // ----------------------------------------------------------
    // NOTE
    // ----------------------------------------------------------

    note: {
      type: Number,
      min: 1,
      max: 5,
      default: 5
    },

    // ----------------------------------------------------------
    // COMMENTAIRE
    // ----------------------------------------------------------

    commentaire: {
      type: String,
      required: true,
      trim: true
    },

    // ----------------------------------------------------------
    // DATE DU RETOUR
    // ----------------------------------------------------------

    date: {
      type: Date,
      default: Date.now
    }
  },
  {
    _id: true
  }
);


// ============================================================
// 🌱 PLANTE
// ============================================================

const PlantSchema = new mongoose.Schema(
  {

    // ==========================================================
    // 🌿 IDENTITÉ
    // ==========================================================

    nomCommun: {
      type: String,
      required: true,
      trim: true,
      index: true
    },

    nomScientifique: {
      type: String,
      required: true,
      trim: true,
      index: true
    },

    famille: {
      type: String,
      trim: true,
      index: true
    },


    // ==========================================================
    // 📝 DESCRIPTION
    // ==========================================================

    description: {
      type: String,
      required: true,
      trim: true
    },


    // ==========================================================
    // 🌍 ORIGINE
    // ==========================================================

    origine: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 🖼️ IMAGES DE RÉFÉRENCE
    // ==========================================================

    images: {
      type: [PlantImageSchema],

      validate: {
        validator: function (images) {
          return images.length === 5;
        },

        message: 'Une plante doit posséder exactement 5 images.'
      },

      default: []
    },


    // ==========================================================
    // 🎨 COULEURS PRINCIPALES
    // ==========================================================

    couleursPrincipal: {
      type: [String],
      default: []
    },


    // ==========================================================
    // 🌸 FLORAISON
    // ==========================================================

    periodeFloraison: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 🍎 RÉCOLTE
    // ==========================================================

    periodeRecolte: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 🔄 CYCLE DE VIE
    // ==========================================================

    cycle: {
      type: String,
      trim: true
    },


    // ==========================================================
    // ☀️ EXPOSITION
    // ==========================================================

    exposition: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 💧 ARROSAGE
    // ==========================================================

    arrosage: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 🌱 SOL
    // ==========================================================

    sol: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 🌡️ TEMPÉRATURE
    // ==========================================================

    temperatureMin: {
      type: Number
    },

    temperatureMax: {
      type: Number
    },


    // ==========================================================
    // 💦 HUMIDITÉ
    // ==========================================================

    humidite: {
      type: String,
      trim: true
    },


    // ==========================================================
    // ☠️ PARTIES DANGEREUSES
    // ==========================================================

    partiesDangereuses: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 🍳 USAGE CULINAIRE
    // ==========================================================

    usageCulinaire: {
      type: String,
      trim: true
    },


    // ==========================================================
    // 💬 RETOURS DES AUTRES PERSONNES
    // ==========================================================

    retour: {
      type: [PlantRetourSchema],
      default: []
    }

  },

  // ============================================================
  // ⏱️ DATES AUTOMATIQUES
  // ============================================================

  {
    timestamps: true
  }
);


// ============================================================
// 🔎 INDEX TEXTE
// ============================================================

PlantSchema.index({
  nomCommun: 'text',
  nomScientifique: 'text',
  famille: 'text',
  description: 'text',
  origine: 'text',
  usageCulinaire: 'text'
});


// ============================================================
// 📤 EXPORT
// ============================================================

module.exports = mongoose.model('Plant', PlantSchema);
